pub fn l(locale_name: &str) -> &'static LocaleStrings {
    let lower = locale_name.trim().to_ascii_lowercase();
    if lower == "en_gb" || lower == "en-gb" {
        &EN_GB
    } else if lower.starts_with("de") {
        &DE_DE
    } else if lower.starts_with("fr") {
        &FR_FR
    } else if lower.starts_with("es") {
        &ES_ES
    } else if lower.starts_with("ja") {
        &JA_JP
    } else {
        &EN_US
    }
}

